# Writes ui/start_screen.json from the game's own start screen: the mod's title
# screen (src/title.cpp) over invisible game buttons, and the vanilla one behind a
# toggle. Run with the path to a version's vanilla start_screen.json.
import json, re, sys

def load(path):
    # the game's UI files allow // comments, strip them outside of strings
    text = open(path, encoding="utf-8").read()
    text = re.sub(r'("(?:\\.|[^"\\])*")|//[^\n]*|/\*.*?\*/', lambda m: m.group(1) or "", text, flags=re.S)
    return json.loads(re.sub(r",(\s*[\]}])", r"\1", text))

vanilla = load(sys.argv[1])["start_screen_content"]["controls"]

# Same spots as src/title.cpp's buttons; the mod draws them, these only take the clicks
buttons = [
    ("play", "button.menu_play", 0.325, 0.52, 0.35, 0.055),
    ("servers", "button.menu_servers", 0.325, 0.595, 0.35, 0.055),
    ("realms", "button.menu_realms", 0.325, 0.67, 0.35, 0.055),
    ("settings", "button.menu_settings", 0.325, 0.745, 0.17, 0.055),
    ("profile", "button.menu_profile", 0.725, 0.52, 0.24, 0.055),
    ("wardrobe", "button.to_profile_screen", 0.725, 0.595, 0.24, 0.055),
    ("inbox", "button.menu_inbox", 0.725, 0.67, 0.24, 0.055),
]
pct = lambda v: f"{v * 100:.2f}%"
clear = "textures/ui/twoclient/clear"
place = lambda x, y, w, h: {"anchor_from": "top_left", "anchor_to": "top_left",
                            "size": [pct(w), pct(h)], "offset": [pct(x), pct(y)]}
shown_when = lambda on: [{"binding_type": "view", "source_control_name": "twoclient_vanilla",
                          "source_property_name": "#toggle_state" if on else "(not #toggle_state)",
                          "target_property_name": "#visible"}]

ours = [{"twoclient_mark": {
    "type": "image", "texture": "textures/ui/twoclient/white", "color": [1 / 255, 254 / 255, 2 / 255],
    "size": [2, 2], "anchor_from": "top_left", "anchor_to": "top_left", "layer": 100}}]
for name, target, x, y, w, h in buttons:
    ours.append({f"twoclient_{name}@common_buttons.light_text_button": {
        **place(x, y, w, h), "$pressed_button_name": target, "$button_text": "",
        "$default_button_texture": clear, "$hover_button_texture": clear,
        "$pressed_button_texture": clear, "$locked_button_texture": clear, "$border_visible": False}})
# the vanilla side gets its own mark, so the mod can draw the way back there too
vanilla = vanilla + [{"twoclient_vanilla_mark": {
    "type": "image", "texture": "textures/ui/twoclient/white", "color": [2 / 255, 1 / 255, 254 / 255],
    "size": [2, 2], "anchor_from": "top_left", "anchor_to": "top_left", "layer": 100}}]

ui = {"namespace": "start", "start_screen_content": {"controls": [
    {"twoclient_screen": {"type": "panel", "bindings": shown_when(False), "controls": ours}},
    {"vanilla_screen": {"type": "panel", "bindings": shown_when(True), "controls": vanilla}},
    # the switch between them, under the mod's top-left button on the OneClient side
    # invisible: the mod draws it on both sides
    {"twoclient_vanilla_toggle_panel": {
        "type": "panel", **place(0.012, 0.035, 0.11, 0.052), "layer": 50, "alpha": 0, "propagate_alpha": True,
        "controls": [{"twoclient_vanilla_toggle@common_toggles.light_text_toggle": {
            "size": ["100%", "100%"], "$toggle_view_binding_name": "twoclient_vanilla", "$button_text": ""}}]}},
]}}
open("ui/start_screen.json", "w").write("// Generated by make_ui.py\n" + json.dumps(ui, indent=1) + "\n")
